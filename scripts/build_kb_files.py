def build_calendar_pdf() -> Path:
    """学校官网公开的 2024-2025 学年校历 PDF（真实长文档）。"""
    out = KB_DIR / "北华大学2024-2025学年校历.pdf"
    if out.exists() and out.stat().st_size > 10000:
        return out
    try:
        import httpx

        r = httpx.get(CALENDAR_URL, timeout=60, follow_redirects=True, headers={"User-Agent": "Mozilla/5.0"})
        if r.status_code == 200 and r.content[:4] == b"%PDF":
            out.write_bytes(r.content)
            return out
        print(f"校历 PDF 下载失败：HTTP {r.status_code}")
    except Exception as e:
        print(f"校历 PDF 下载异常：{e}")
    return out if out.exists() else None


